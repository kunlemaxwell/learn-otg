"use client";
import { createRoot } from "react-dom/client";
import { flushSync } from "react-dom";
import { LessonRenderer } from "@/components/LessonRenderer";
import { allLessons, lessonPages } from "./courses";
import type { Course } from "./course-types";
import { dataUrlToBlob, downloadBlob, elementToPng, pngsToPdf, slug } from "./export";
export type ExportScope = "page" | "lesson" | "course";
export async function exportCourse(c: Course, lessonId: string, scope: "lesson" | "course", kind: "png" | "pdf", onProgress: (text: string) => void) {
  const pages = allLessons(c).filter(x => scope === "course" || x.lesson.id === lessonId).flatMap(({ section, lesson }) => lessonPages(lesson, c.options).filter(p => p.status === "ready" && p.code).map(p => ({ section, lesson, page: p })));
  if (!pages.length) throw new Error("No finished pages to save yet.");
  const host = document.createElement("div");
  host.className = `export-capture m-${c.mood}`;
  host.style.cssText = "position:fixed;left:-10000px;top:0;width:760px;pointer-events:none;background:var(--paper);padding:24px;";
  document.body.appendChild(host);
  const capture = document.createElement("div");
  host.appendChild(capture);
  const root = createRoot(capture);
  const title = scope === "course" ? c.title : pages[0].lesson.title;
  const quiz = c.quizzes.filter(q => q.status === "ready" && q.questions.length && (scope === "course" || q.lessonId === lessonId));
  async function* images() {
    let i = 0;
    for (const item of pages) {
      onProgress(`Saving page ${++i} of ${pages.length}…`);
      flushSync(() => root.render(<><header className="export-heading"><h1>{c.title}</h1><p>{item.section.title} · {item.lesson.title} · {item.page.title}</p></header><LessonRenderer code={item.page.code!} title={item.lesson.title} mood={c.mood} />{item.page.answers?.length ? <section className="card"><h2>Your saved answers</h2>{item.page.answers.map((a, n) => <div key={n}><strong>{a.question}</strong><p>{a.response}</p>{a.feedback && <p>{a.feedback}</p>}</div>)}</section> : null}</>));
      yield { name: `${String(i).padStart(3, "0")}-${slug(item.lesson.title)}-${slug(item.page.title)}.png`, png: await elementToPng(capture, { pixelRatio: 1.5 }) };
    }
    for (const q of quiz) {
      onProgress(`Saving ${q.title}…`);
      flushSync(() => root.render(<section className="card export-heading"><h1>{q.title}</h1>{q.questions.map((x, i) => <div key={i}><h2>{i+1}. {x.q}</h2><ol>{x.options.map((o, n) => <li key={n}>{o}</li>)}</ol><p>Answer: {x.options[x.answer]}</p><p>{x.why}</p></div>)}</section>));
      yield { name: `${String(++i).padStart(3, "0")}-${slug(q.title)}.png`, png: await elementToPng(capture, { pixelRatio: 1.5 }) };
    }
  }
  try {
    if (kind === "pdf") downloadBlob(await pngsToPdf(images(), title), `${slug(title)}-${scope}-so-far.pdf`);
    else {
      const { default: JSZip } = await import("jszip");
      const zip = new JSZip();
      for await (const item of images()) zip.file(item.name, dataUrlToBlob(item.png));
      zip.file("contents.txt", `${title}\nFinished pages: ${pages.length}\nGenerated quizzes: ${quiz.length}\nSaved on ${new Date().toLocaleString()}\nOnly material written so far is included. Unwritten pages are not generated by exporting.\n`);
      downloadBlob(await zip.generateAsync({ type: "blob" }), `${slug(title)}-${scope}-images.zip`);
    }
  } finally { root.unmount(); host.remove(); }
}
